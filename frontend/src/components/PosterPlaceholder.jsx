export function hueFor(str = '') {
  let h = 0
  for (let i = 0; i < str.length; i++) h = (h * 31 + str.charCodeAt(i)) % 360
  return h
}

export function BrandLogo({ size = '38%', className = '' }) {
  return (
    <svg viewBox="0 0 1254 1254" style={{ width: size }} className={className} aria-hidden="true">
      <rect width="1254" height="1254" rx="282" fill="#fdd008" />
      <path d={GLYPH} fill="#0a0b0a" />
    </svg>
  )
}

function PosterPlaceholder({ name = '', showTitle = false, pulse = false }) {
  const h = hueFor(name)
  return (
    <div
      className="absolute inset-0 flex flex-col items-center justify-center"
      style={{
        background: `radial-gradient(120% 80% at 50% 28%, hsl(${h} 55% 30%) 0%, hsl(${(h + 40) % 360} 55% 15%) 70%, hsl(${(h + 70) % 360} 50% 9%) 100%)`,
      }}
    >
      <BrandLogo className={pulse ? 'animate-pulse' : ''} />
      {showTitle && name ? (
        <span className="mt-2 px-2 text-center text-[10px] leading-tight text-white/70 line-clamp-2">{name}</span>
      ) : null}
    </div>
  )
}

export default memo(PosterPlaceholder)
