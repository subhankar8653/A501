export function translate(langCode, key) {
  const lang = dict[langCode] || dict.en
  // Fallback: Hindi/Hinglish -> Hinglish; baaki sab bhasha -> English (Hinglish nahi).
  const fb = langCode === 'hinglish' || langCode === 'hi' ? dict.hinglish : dict.en
  return lang[key] || fb[key] || dict.en[key] || dict.hinglish[key] || key
}

// Non-hook helper (toasts, class components, error boundaries): current saved language
// padhta hai aur {vars} replace karta hai.
export function tr(key, vars) {
  let code = 'en'
  try { code = localStorage.getItem('a501_language') || 'en' } catch { /* ignore */ }
  let s = translate(code, key)
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]))
  return s
}

